/// Resolves one Symbol code through its Annex D.5 name and the Adobe Glyph List.
#[must_use]
pub(super) fn symbol_text(code: u8) -> Option<char> {
    let name = SYMBOL_ENCODING[usize::from(code)]?;
    single_scalar(super::agl::lookup(name.as_bytes())?)
}

/// Resolves one `ZapfDingbats` code through its Annex D.6 name.
///
/// `aNN` names use the Adobe `ZapfDingbats` glyph list; a name outside it falls
/// back to the Adobe Glyph List (for example `space`).
#[must_use]
pub(super) fn zapf_dingbats_text(code: u8) -> Option<char> {
    let name = ZAPF_DINGBATS_ENCODING[usize::from(code)]?;
    zapf_dingbats_char(name.as_bytes())
        .or_else(|| single_scalar(super::agl::lookup(name.as_bytes())?))
}

/// Resolves one glyph name in the Adobe `ZapfDingbats` glyph list.
///
/// The list names dingbats `a1` through `a206`; a name outside that pattern or
/// range has no dingbat Unicode value.
#[must_use]
pub(super) fn zapf_dingbats_char(name: &[u8]) -> Option<char> {
    let digits = name.strip_prefix(b"a")?;
    if digits.is_empty() || !digits.iter().all(u8::is_ascii_digit) {
        return None;
    }
    let index = std::str::from_utf8(digits).ok()?.parse::<usize>().ok()?;
    ZAPF_DINGBATS_UNICODE.get(index).copied().flatten()
}

/// Accepts only a name that maps to exactly one Unicode scalar.
fn single_scalar(text: &str) -> Option<char> {
    let mut characters = text.chars();
    let first = characters.next()?;
    characters.next().is_none().then_some(first)
}
